function makeSemanticBlock(
  category: '角色' | '主体',
  name: string,
  icon: string,
  index: number,
): BlockDef {
  const isRole = category === '角色'
  // 用固定的语义类配色：角色 = role（靛蓝），主体 = external（灰）
  const cls = isRole ? semanticClass('role')! : semanticClass('external')!
  const { fill, stroke, color: textColor } = cls
  return {
    id: `builtin.${isRole ? 'role' : 'subject'}.${index}`,
    name,
    category,
    icon,
    builtin: true,
    kind: 'node',
    shape: isRole ? 'stadium' : 'subroutine',
    fill,
    stroke,
    textColor,
    width: isRole ? 132 : 156,
    height: 52,
    fields: [],
    ports: DEFAULT_PORTS,
    className: cls.name,
    description: isRole ? `角色：${name}` : `主体（业务主体）：${name}`,
  }
}

export const SEMANTIC_BLOCKS: BlockDef[] = [
  ...ROLE_ITEMS.map(([name, icon], i) => makeSemanticBlock('角色', name, icon, i)),
  ...SUBJECT_ITEMS.map(([name, icon], i) => makeSemanticBlock('主体', name, icon, i)),
]

BUILTIN_BLOCKS.push(...SEMANTIC_BLOCKS)

